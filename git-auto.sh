#!/bin/bash
# Workflow git rapide (évite d'appeler l'IA pour les commits/push)
set -e

if [ "$1" = "--help" ] || [ "$1" = "-h" ] || [ -z "$1" ]; then
  echo "Usage: ./git-auto.sh <commande> [args]"
  echo ""
  echo '  status                        -> branche courante, commits en avance, fichiers modifies'
  echo '  commit "fix(vX.Y.Z): desc"    -> git add -A + commit avec pied Vibe + grep <NOM-PROSCRIT>'
  echo '  push                          -> push la branche (hook pre-push bloque les .click)'
  echo '  pr "Titre de la PR"           -> push + cree la PR (gh si installe, sinon URL GitHub)'
  echo '  livraison <version> "titre"    -> assemble livraison/<app>-<version>/ (click + CHANGELOG + README), commit (git add -f)'
  echo '  newfix <nom>                  -> cree fix/<nom> depuis main a jour'
  exit 0
fi

CMD="${1:?Usage: $0 commit|push|pr|newfix|status ...}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
APP_PREFIX="utitibike"
cd "$ROOT"

FOOTER="Built and tested by Mathias — code written by Vibe, reviewed and controlled by Mathias.\nGenerated by Mistral Vibe & control by Mathias.
Co-Authored-By: Mistral Vibe <<EMAIL>> and Mathias"

case "$CMD" in
  commit)
    MSG="${2:?message requis}"
    git add -A
    # Garde-fou confidentialité (règle Mathias 2026-11-01)
    if grep -ri <NOM-PROSCRIT> --exclude-dir=.git --exclude-dir=node_modules --exclude-dir=build --exclude-dir=dist --exclude=AGENTS.md --exclude=check.sh --exclude=git-auto.sh --exclude=menu.sh . 2>/dev/null | grep -q .; then
      echo "ERREUR: '<NOM-PROSCRIT>' détecté dans le working tree — commit annulé (règle confidentialité)"
      exit 1
    fi
    git commit -m "$MSG

$FOOTER"
    echo "OK: $(git log --oneline -1)"
    ;;

  push)
    BR=$(git branch --show-current)
    echo "Push de la branche '$BR'..."
    git push -u origin "$BR" 2>&1 | tail -5
    echo "(le hook pre-push bloque automatiquement tout .click)"
    ;;

  pr)
    TITLE="${2:?titre de la PR requis}"
    BR=$(git branch --show-current)
    git push -u origin "$BR" 2>&1 | tail -3
    if command -v gh >/dev/null 2>&1; then
      gh pr create --title "$TITLE" --body "$(git log main..HEAD --oneline)" 2>&1 | tail -3
    else
      echo "gh non installé — crée la PR manuellement :"
      echo "  https://github.com/mathiasmb31/utoutlook/compare/$BR?expand=1"
    fi
    ;;

  newfix)
    NAME="${2:?nom du fix requis}"
    git checkout main
    git pull --ff-only origin main 2>/dev/null || true
    git checkout -b "fix/$NAME"
    echo "Branche fix/$NAME créée depuis main"
    ;;

  livraison)
    VER="${2:?version requise (ex: 4.0.61)}"
    TITRE="${3:-livraison $APP_PREFIX $VER}"
    WS="$(cd "$ROOT/.." && pwd)"
    LIV="$WS/livraison/$APP_PREFIX-$VER"
    mkdir -p "$LIV"
    CLICK="$(find "$ROOT" -maxdepth 2 -name '*.click' -not -path '*/node_modules/*' -not -path '*/build/*' 2>/dev/null | sort -V | tail -1)"
    if [ -n "$CLICK" ]; then
      cp -f "$CLICK" "$LIV/"
      echo "click copié: $(basename "$CLICK")"
    else
      echo "AUCUN .click trouvé sous $ROOT — build manuel d'abord (./build-deploy.sh)"
    fi
    for f in CHANGELOG.md README.txt; do
      [ -f "$LIV/$f" ] || echo "MANQUANT: $LIV/$f — rédige-le avant le commit"
    done
    cd "$WS"
    git add livraison/
    [ -n "$CLICK" ] && git add -f "$LIV/"*.click 2>/dev/null
    git commit -m "$TITRE

$FOOTER"
    echo "OK: $(git log --oneline -1)"
    echo "Reste: push filtré (le hook pre-push bloque les .click) puis PR:"
    echo "  cd $WS && git push origin main   # si le hook bloque à cause du .click, voir base-de-connaissances/restauration-workspace-vibe-2026-11-06.md (push filtré)"
    ;;

  status)
    echo "Branche: $(git branch --show-current)"
    echo "Commits en avance sur origin/main: $(git rev-list --count origin/main..HEAD 2>/dev/null || echo '?')"
    echo "Fichiers modifiés non commités:"
    git status --short | head -10
    ;;

  *)
    echo "Commandes: commit|push|pr|newfix|status"
    exit 1
    ;;
esac
